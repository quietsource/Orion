import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const languageDirectory = path.join(root, 'node_modules', 'highlight.js', 'es', 'languages');
const files = (await readdir(languageDirectory)).filter(file => file.endsWith('.js') && !file.endsWith('.js.js')).sort();
const imports = files.map((file, index) => `// @ts-ignore Highlight.js ships language modules without individual TypeScript declarations.\nimport language${index} from '../../node_modules/highlight.js/es/languages/${file}';`).join('\n');
const entries = files.map((file, index) => `  ${JSON.stringify(file.slice(0, -3))}: language${index},`).join('\n');
const source = `// Generated by scripts/generate-highlight-languages.mjs.\n${imports}\n\nexport const languageModules = {\n${entries}\n};\n`;
await writeFile(path.join(root, 'src', 'renderer', 'highlight-languages.generated.ts'), source);
